/// Boxed future, used where eager loading recurses into related models.
pub type BoxFuture<'a, T> = Pin<Box<dyn Future<Output = T> + Send + 'a>>;

/// A relation field: empty until loaded with [`Query::with`] or
/// [`Model::load`].
///
/// - `has_many`, `belongs_to_many`, `has_many_through`, `morph_many`,
///   `morph_to_many`, `morphed_by_many`: `Rel<Vec<Post>>`
/// - `has_one`, `belongs_to`, `has_one_through`, `morph_one`:
///   `Rel<Option<User>>`, or `Rel<Option<Box<User>>>`
///   when two models point at each other
/// - `#[rustique(count)]` fields filled by [`Query::with_count`]: `Rel<u64>`
///
/// With serde, a loaded relation serializes as its value and a missing one
/// is left out.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub enum Rel<T> {
    /// Not loaded.
    #[default]
    NotLoaded,
    /// Loaded value.
    Loaded(T),
}

impl<T> Rel<T> {
    /// The loaded value.
    ///
    /// # Errors
    ///
    /// [`Error::RelationNotLoaded`] when the relation was not loaded.
    pub fn loaded(&self) -> Result<&T> {
        self.get().ok_or(Error::RelationNotLoaded)
    }

    /// The loaded value, if any.
    pub fn get(&self) -> Option<&T> {
        match self {
            Self::Loaded(value) => Some(value),
            Self::NotLoaded => None,
        }
    }

    /// Whether the relation was loaded.
    pub fn is_loaded(&self) -> bool {
        matches!(self, Self::Loaded(_))
    }

    /// Whether the relation was not loaded; used by serde's `skip_serializing_if`.
    pub fn is_not_loaded(&self) -> bool {
        !self.is_loaded()
    }

    /// Reads `column` if the row has it, for `#[rustique(count)]` fields.
    #[doc(hidden)]
    pub fn from_row(row: &mut Row, column: &str) -> Result<Self>
    where
        T: FromValue,
    {
        match row.take(column) {
            Ok(value) => Ok(Self::Loaded(value)),
            Err(Error::ColumnNotFound(_)) => Ok(Self::NotLoaded),
            Err(error) => Err(error),
        }
    }
}

impl<T: Serialize> Serialize for Rel<T> {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        self.get().serialize(serializer)
    }
}

impl<'de, T: Deserialize<'de>> Deserialize<'de> for Rel<T> {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        T::deserialize(deserializer).map(Self::Loaded)
    }
}

/// What a [`Rel`] holds: every related model, or the first one.
pub trait FromRelated<R> {
    /// Builds the value from the related models of one parent.
    fn from_related(models: Vec<R>) -> Self;
}

impl<R> FromRelated<R> for Vec<R> {
    fn from_related(models: Vec<R>) -> Self {
        models
    }
}

impl<R> FromRelated<R> for crate::Collection<R> {
    fn from_related(models: Vec<R>) -> Self {
        models.into()
    }
}

impl<R> FromRelated<R> for Option<R> {
    fn from_related(models: Vec<R>) -> Self {
        models.into_iter().next()
    }
}

impl<R> FromRelated<R> for Option<Box<R>> {
    fn from_related(models: Vec<R>) -> Self {
        models.into_iter().next().map(Box::new)
    }
}

/// How a parent model finds its related rows; generated by `#[rustique::model]`.
///
/// The parent's `local` columns equal the `remote` columns of the related
/// table, or of the `through` table, which is then joined to the related one.
#[doc(hidden)]
#[derive(Debug, Clone, Copy)]
pub struct Relation {
    pub kind: RelationKind,
    pub related_table: &'static str,
    /// The related model's query, with its soft-delete filter.
    pub related_query: fn() -> QueryBuilder,
    pub local: &'static [&'static str],
    pub remote: &'static [&'static str],
    pub through: Option<Through>,
    /// `(type column, value)` of `morph_one` / `morph_many`: related rows
    /// must also carry the parent's morph type.
    pub morph: Option<(&'static str, &'static str)>,
    /// `latest_of_many` / `oldest_of_many` of a `has_one` / `morph_one`.
    pub of_many: Option<OfMany>,
}

/// Of a parent's related rows, only the one with the highest (or lowest)
/// `column`, ties going to the highest (or lowest) key, like Eloquent's
/// `latestOfMany` / `oldestOfMany`. Rows whose `column` is NULL never win,
/// as `MAX` ignores them.
#[doc(hidden)]
#[derive(Debug, Clone, Copy)]
pub struct OfMany {
    /// The column to rank by; the key when `None`.
    pub column: Option<&'static str>,
    pub descending: bool,
    /// The related model's primary key.
    pub key: &'static [&'static str],
}

/// The attribute that declared a [`Relation`].
#[doc(hidden)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RelationKind {
    HasOne,
    HasMany,
    BelongsTo,
    BelongsToMany,
    HasManyThrough,
    HasOneThrough,
    MorphOne,
    MorphMany,
}

/// `JOIN table ON table.through_key = related.related_key`.
#[doc(hidden)]
#[derive(Debug, Clone, Copy)]
pub struct Through {
    pub table: &'static str,
    pub through_key: &'static [&'static str],
    pub related_key: &'static [&'static str],
    /// Extra pivot columns read into [`Model::pivot`] (`belongs_to_many` only).
    pub pivot: &'static [&'static str],
    /// Creation and update time columns of the pivot table, filled on attach.
    pub timestamps: Option<[&'static str; 2]>,
    /// `(type column, value)` of `morph_to_many` / `morphed_by_many`: pivot
    /// rows must also carry this morph type.
    pub morph: Option<(&'static str, &'static str)>,
}

impl Through {
    /// Pivot columns read into [`Model::pivot`].
    fn pivot_columns(&self) -> impl Iterator<Item = &'static str> {
        self.pivot
            .iter()
            .copied()
            .chain(self.timestamps.into_iter().flatten())
    }
}

impl Relation {
    pub(crate) fn lookup<P: Model>(name: &str) -> Result<Self> {
        P::relation(name).ok_or_else(|| Error::UnknownRelation {
            model: P::TABLE,
            relation: name.to_owned(),
        })
    }

    /// The related model's query, joined to the `through` table, with the
    /// pivot columns selected for [`Model::pivot`]. `columns` (from
    /// `with("posts:id,title")`) replaces the related table's `*`; plain
    /// names are qualified with its table.
    fn related<R: Model>(&self, columns: Option<&[String]>) -> Query<R> {
        let mut query = R::query();
        query.builder = self.of_many(self.join(query.builder));
        if let Some(columns) = columns {
            let qualified = columns.iter().map(|column| match column.contains('.') {
                true => column.clone(),
                false => format!("{}.{column}", self.related_table),
            });
            query.builder = std::mem::take(&mut query.builder).select(qualified);
        }
        if let Some(through) = self.through {
            for column in through.pivot_columns() {
                let alias = format!("orm_pivot_{column}");
                let selected = format!("{}.{column} as {alias}", through.table);
                query.builder = query.builder.add_select([selected]);
                query.pivot.push((alias, column));
            }
        }
        query
    }

    /// `remote` columns, qualified with their table.
    fn remote_columns(&self) -> Vec<String> {
        let table = self.through.map_or(self.related_table, |t| t.table);
        self.remote.iter().map(|c| format!("{table}.{c}")).collect()
    }

    /// Joins the `through` table, keeping only the related table's columns,
    /// or filters on the morph type.
    fn join(&self, query: QueryBuilder) -> QueryBuilder {
        if let Some((column, value)) = self.morph {
            return query.where_(format!("{}.{column}", self.related_table), "=", value);
        }
        let Some(through) = self.through else {
            return query;
        };
        let keys = through.through_key.iter().zip(through.related_key);
        let query = match through.morph {
            Some((column, value)) => {
                query.where_(format!("{}.{column}", through.table), "=", value)
            }
            None => query,
        };
        query
            .select([format!("{}.*", self.related_table)])
            .join_with(through.table, |join| {
                keys.fold(join, |join, (through_key, related_key)| {
                    join.on(
                        format!("{}.{through_key}", through.table),
                        "=",
                        format!("{}.{related_key}", self.related_table),
                    )
                })
            })
    }

    /// Keeps the related row that [`OfMany`] picks for each parent:
    /// `key IN (SELECT key FROM (SELECT key, ROW_NUMBER() OVER (PARTITION BY
    /// remote ORDER BY column DESC, key DESC) AS orm_rank FROM related WHERE
    /// ...) orm_ranked WHERE orm_rank = 1)`. The ranking sees the related
    /// query's soft-delete filter, global scopes and the relation's `scope`,
    /// so `latest_of_many` with a scope picks the latest matching row.
    fn of_many(&self, query: QueryBuilder) -> QueryBuilder {
        let Some(of_many) = self.of_many else {
            return query;
        };
        let &[key] = of_many.key else {
            let mut query = query;
            query.fail(format!(
                "`latest_of_many` / `oldest_of_many` need a single-column key on `{}`",
                self.related_table
            ));
            return query;
        };
        let table = self.related_table;
        let key_column = format!("{table}.{key}");
        let order = |column: String| Order::Column {
            column,
            descending: of_many.descending,
        };
        let mut ranked = self.join((self.related_query)());
        let mut orders = vec![order(key_column.clone())];
        if let Some(column) = of_many.column.filter(|c| *c != key) {
            let column = format!("{table}.{column}");
            ranked = ranked.where_not_null(column.clone());
            orders.insert(0, order(column));
        }
        ranked.columns = vec![
            Expr::Column(format!("{key_column} as orm_key")),
            Expr::RowNumber {
                partition: self.remote_columns(),
                order: orders,
                alias: "orm_rank".to_owned(),
            },
        ];
        let latest = QueryBuilder::from_sub(ranked, "orm_ranked")
            .select(["orm_ranked.orm_key"])
            .where_("orm_ranked.orm_rank", "=", 1);
        query.where_in_sub(key_column, latest)
    }

    /// Related rows of the row of table `parent`, for `EXISTS` and counts.
    /// When the related (or pivot) table is `parent` itself, as in a
    /// `parent` / `children` relation, it is aliased `orm_self` inside, like
    /// Eloquent's `laravel_reserved_0`, so `parent.` still means the outer row.
    pub(crate) fn correlated(&self, parent: &str) -> QueryBuilder {
        const ALIAS: &str = "orm_self";
        let mut query = self.of_many(self.join((self.related_query)()));
        let mut remote = self.remote_columns();
        let tables = [Some(self.related_table), self.through.map(|t| t.table)];
        if let Some(table) = tables.into_iter().flatten().find(|t| *t == parent) {
            query.alias_table(table, ALIAS);
            let prefix = format!("{table}.");
            for column in &mut remote {
                if let Some(rest) = column.strip_prefix(&prefix) {
                    *column = format!("{ALIAS}.{rest}");
                }
            }
        }
        remote
            .into_iter()
            .zip(self.local)
            .fold(query, |query, (remote, local)| {
                query.where_column(remote, "=", format!("{parent}.{local}"))
            })
    }
}

/// Values of `columns` in `model`.
pub(crate) fn column_values<M: Model>(model: &M, columns: &[&str]) -> Result<Vec<Value>> {
    let values = model.to_values();
    columns
        .iter()
        .map(|column| {
            let index = M::COLUMNS.iter().position(|c| c == column).ok_or_else(|| {
                Error::InvalidQuery(format!(
                    "relation key `{column}` is not a column of model `{}`",
                    M::TABLE
                ))
            })?;
            Ok(values[index].clone())
        })
        .collect()
}

/// Hashable form of a key, equal for equal integers whatever their
/// [`Value`] variant (Oracle returns numbers as decimals). `None` when a
/// part is NULL: NULL keys match nothing.
fn key_string(values: &[Value]) -> Option<String> {
    let mut key = String::new();
    for value in values {
        // Writing to a String cannot fail.
        let _ = match (value, integer(value)) {
            (Value::Null, _) => return None,
            (_, Some(n)) => write!(key, "i{n}|"),
            (Value::String(s), _) => write!(key, "s{}:{s}|", s.len()),
            (other, _) => write!(key, "{other:?}|"),
        };
    }
    Some(key)
}

/// Keys per query when loading related rows: one `IN` list on Oracle (at
/// most 1000 items), far below the 65,535 bindings of a statement, and few
/// statement shapes for MySQL's prepared statement cache.
const KEYS_PER_QUERY: usize = 1000;

/// `items` in batches of [`KEYS_PER_QUERY`].
fn batches<T>(items: Vec<T>) -> impl Iterator<Item = Vec<T>> {
    let mut items = items.into_iter();
    std::iter::from_fn(move || {
        let batch: Vec<T> = items.by_ref().take(KEYS_PER_QUERY).collect();
        (!batch.is_empty()).then_some(batch)
    })
}

/// `WHERE column IN (...)` for one column, `(a, b) IN (...)` for several.
pub(crate) fn where_keys(
    query: QueryBuilder,
    columns: Vec<String>,
    keys: Vec<Vec<Value>>,
) -> QueryBuilder {
    if let [column] = &columns[..] {
        query.where_in(column, keys.into_iter().flatten())
    } else {
        query.where_rows_in(columns, keys)
    }
}

/// The constraint of a relation: its `scope`, or `|q| q`.
#[doc(hidden)]
pub type RelationScope<R> = fn(Query<R>) -> Query<R>;

/// `parent.name()`: the related models of one parent, as a query.
#[doc(hidden)]
pub fn query<P: Model, R: Model>(parent: &P, name: &str, scope: RelationScope<R>) -> Query<R> {
    let relation = Relation::lookup::<P>(name);
    let values = relation.and_then(|r| Ok((r, column_values(parent, r.local)?)));
    match values {
        Ok((relation, values)) => {
            let mut query = super::scope(relation.related::<R>(None), scope);
            if let Some(message) = lazy_load::<P>(parent, name) {
                query.builder.fail(message);
            }
            if values.iter().any(Value::is_null) {
                query.builder = query.builder.where_raw("0 = 1", []); // an unsaved parent has no relatives
            }
            for (column, value) in relation.remote_columns().into_iter().zip(values) {
                query.builder = query.builder.where_(column, "=", value);
            }
            query
        }
        Err(error) => {
            let mut query = R::query();
            query.builder.fail(error.to_string());
            query
        }
    }
}

/// What happens when a relation is queried lazily on a model loaded with
/// others, the usual sign of an N+1 query loop; see [`prevent_lazy_loading`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum LazyLoading {
    /// Nothing; the default.
    Allow,
    /// Logs a warning (target `rustique::lazy`, level `WARN`) naming the model and relation.
    Warn,
    /// The relation query fails with [`Error::InvalidQuery`].
    Deny,
}

static LAZY_LOADING: AtomicU8 = AtomicU8::new(0);

/// Flags lazy relation queries (`user.posts()`, `comment.commentable(db)`)
/// on models that were loaded together with other models, like Eloquent's
/// `preventLazyLoading`: in a loop over query results each such call is one
/// more query, where [`Query::with`] would load them all at once. Models
/// loaded alone, by `find` or `first`, are never flagged.
///
/// Typically enabled outside production:
///
/// ```
/// rustique::prevent_lazy_loading(if cfg!(debug_assertions) {
///     rustique::LazyLoading::Deny
/// } else {
///     rustique::LazyLoading::Allow
/// });
/// ```
pub fn prevent_lazy_loading(mode: LazyLoading) {
    let value = match mode {
        LazyLoading::Allow => 0,
        LazyLoading::Warn => 1,
        LazyLoading::Deny => 2,
    };
    LAZY_LOADING.store(value, Ordering::Relaxed);
}

/// Warns about a lazy load of `relation` on `parent`, or returns the error
/// message when lazy loading is denied.
fn lazy_load<P: Model>(parent: &P, relation: &str) -> Option<String> {
    if !parent.meta().siblings {
        return None;
    }
    match LAZY_LOADING.load(Ordering::Relaxed) {
        1 => {
            tracing::warn!(
                target: "rustique::lazy",
                model = P::TABLE,
                relation,
                "lazy loading on a model loaded with others; eager-load it with `with`"
            );
            None
        }
        2 => Some(format!(
            "lazy loading `{relation}` on a `{}` model loaded with others; eager-load it with `with`",
            P::TABLE
        )),
        _ => None,
    }
}

/// Eager loading of relation `name` into `field` of every parent: one query
/// per [`KEYS_PER_QUERY`] parents, then `nested` relations on the related models.
#[doc(hidden)]
pub async fn load<P: Model, R: Model + Clone, T: FromRelated<R>, E: Executor>(
    db: &E,
    parents: &mut [P],
    name: &str,
    nested: Nested,
    field: fn(&mut P) -> &mut Rel<T>,
    scope: RelationScope<R>,
) -> Result<()> {
    let relation = Relation::lookup::<P>(name)?;
    let mut keys = Vec::new();
    // Each parent's key, and how many parents share it.
    let mut parent_keys = Vec::with_capacity(parents.len());
    let mut sharing: HashMap<String, usize> = HashMap::new();
    for parent in parents.iter() {
        let values = column_values(parent, relation.local)?;
        let key = key_string(&values);
        if let Some(key) = &key {
            let count = sharing.entry(key.clone()).or_default();
            if *count == 0 {
                keys.push(values);
            }
            *count += 1;
        }
        parent_keys.push(key);
    }

    let mut groups: HashMap<String, Vec<R>> = HashMap::new();
    if !keys.is_empty() {
        let remote = relation.remote_columns();
        let mut query = super::scope(relation.related::<R>(nested.columns()), scope);
        let mut builder = nested.constrain(query.builder);
        if builder.columns.is_empty() {
            builder = builder.select([format!("{}.*", R::TABLE)]);
        }
        // The matched key travels along under a fixed alias, so models of
        // `through` relations can be grouped too.
        let aliases: Vec<String> = (0..remote.len()).map(|i| format!("orm_key_{i}")).collect();
        let selected = remote
            .iter()
            .zip(&aliases)
            .map(|(c, a)| format!("{c} as {a}"));
        query.builder = builder.add_select(selected);
        query.eager = nested.paths;

        let mut rows = Vec::new();
        for batch in batches(keys) {
            let mut batch_query = query.clone();
            batch_query.builder = where_keys(batch_query.builder, remote.clone(), batch);
            rows.extend(batch_query.into_builder().get(db).await?.into_inner());
        }
        let row_keys = rows
            .iter()
            .map(|row| {
                let values = aliases
                    .iter()
                    .map(|alias| row.get::<Value>(alias))
                    .collect::<Result<Vec<_>>>()?;
                Ok(key_string(&values))
            })
            .collect::<Result<Vec<_>>>()?;
        let models = query.hydrate(db, rows).await?;
        for (key, model) in row_keys.into_iter().zip(models) {
            if let Some(key) = key {
                groups.entry(key).or_default().push(model);
            }
        }
    }

    for (parent, key) in parents.iter_mut().zip(parent_keys) {
        let related = key.and_then(|key| take_or_clone(&mut groups, &mut sharing, key));
        *field(parent) = Rel::Loaded(T::from_related(related.unwrap_or_default()));
    }
    Ok(())
}

/// The value of `key`: cloned while other parents still need it, moved out
/// for the last one, so unshared related models are never copied.
fn take_or_clone<K: Eq + std::hash::Hash, V: Clone>(
    values: &mut HashMap<K, V>,
    sharing: &mut HashMap<K, usize>,
    key: K,
) -> Option<V> {
    let left = sharing.get_mut(&key)?;
    *left -= 1;
    if *left == 0 {
        values.remove(&key)
    } else {
        values.get(&key).cloned()
    }
}

/// The type a `morph_to` field points at: an enum with one variant per
/// possible parent model, from `#[derive(rustique::MorphTo)]`.
///
/// ```
/// use rustique::prelude::*;
///
/// #[rustique::model(table = "posts")]
/// #[derive(Debug, Clone, Default)]
/// pub struct Post {
///     pub id: i64,
///     #[rustique(morph_many(Comment, name = "commentable"))]
///     pub comments: Rel<Vec<Comment>>,
/// }
///
/// #[rustique::model(table = "videos")]
/// #[derive(Debug, Clone, Default)]
/// pub struct Video {
///     pub id: i64,
/// }
///
/// #[derive(Debug, Clone, rustique::MorphTo)]
/// pub enum Commentable {
///     Post(Post),
///     Video(Video),
/// }
///
/// #[rustique::model(table = "comments")]
/// #[derive(Debug, Clone, Default)]
/// pub struct Comment {
///     pub id: i64,
///     pub commentable_type: String, // "posts" or "videos": the parent's morph alias
///     pub commentable_id: i64,
///     #[rustique(morph_to)]
///     pub commentable: Rel<Option<Commentable>>,
/// }
///
/// let post = Post { id: 7, ..Default::default() };
/// let sql = post.comments().to_sql(Dialect::MySql)?.sql;
/// assert_eq!(
///     sql,
///     "SELECT * FROM `comments` WHERE `comments`.`commentable_type` = ? \
///      AND `comments`.`commentable_id` = ?",
/// );
/// # Ok::<(), rustique::Error>(())
/// ```
pub trait MorphTo: Clone + Send + Sync + 'static {
    /// The models of the variant whose morph alias is `alias`, with primary
    /// key in `keys`, each with its key.
    ///
    /// # Errors
    ///
    /// [`Error::UnknownMorphType`] when no variant has the alias, plus
    /// database and decode errors.
    #[doc(hidden)]
    fn load_morph<E: Executor>(
        db: &E,
        alias: &str,
        keys: Vec<Value>,
        nested: Nested,
    ) -> impl Future<Output = Result<Vec<(Value, Self)>>> + Send;

    /// One entry per variant, for `where_has_morph`.
    #[doc(hidden)]
    fn targets() -> Vec<MorphTarget> {
        Vec::new()
    }
}

/// A model a `morph_to` relation can point at; generated by `#[derive(rustique::MorphTo)]`.
#[doc(hidden)]
#[derive(Debug, Clone, Copy)]
pub struct MorphTarget {
    pub alias: &'static str,
    pub table: &'static str,
    pub key: &'static [&'static str],
    /// The model's query, with its soft-delete filter and global scopes.
    pub query: fn() -> QueryBuilder,
}

/// Models of `R` with primary key in `keys`, for [`MorphTo::load_morph`].
#[doc(hidden)]
pub async fn morph_models<R: Model, T, E: Executor>(
    db: &E,
    keys: Vec<Value>,
    nested: Nested,
    wrap: fn(R) -> T,
) -> Result<Vec<(Value, T)>> {
    let &[key] = R::PRIMARY_KEY else {
        return Err(Error::InvalidQuery(format!(
            "`morph_to` needs a single-column key on `{}`",
            R::TABLE
        )));
    };
    let mut query = nested.morph_counts(R::query());
    if let Some(columns) = nested.columns() {
        let qualified = (columns.iter()).map(|c| match c.contains('.') {
            true => c.clone(),
            false => format!("{}.{c}", R::TABLE),
        });
        query.builder = query.builder.add_select(qualified);
    }
    query.builder = nested.constrain(query.builder);
    query.eager = nested.paths;
    let column = format!("{}.{key}", R::TABLE);
    let mut rows = Vec::new();
    for batch in batches(keys) {
        let batch_query = query.clone().where_in(column.clone(), batch);
        rows.extend(batch_query.into_builder().get(db).await?.into_inner());
    }
    query
        .hydrate(db, rows)
        .await?
        .into_iter()
        .map(|model| Ok((column_values(&model, &[key])?.remove(0), wrap(model))))
        .collect()
}

/// The `(type, id)` a `morph_to` field points at, if both are set.
fn morph_target<P: Model>(parent: &P, columns: [&str; 2]) -> Result<Option<(String, Value)>> {
    let mut values = column_values(parent, &columns)?;
    let id = values.pop().expect("two columns");
    let alias = Option::<String>::from_value(values.pop().expect("two columns"))
        .map_err(|source| Error::decode(Some(P::TABLE), columns[0], source))?;
    // An empty type points nowhere, as in Eloquent (Oracle reads it as NULL anyway).
    Ok(alias
        .filter(|alias| !alias.is_empty() && !id.is_null())
        .map(|alias| (alias, id)))
}

/// `comment.commentable(db)`: the model a `morph_to` field points at.
#[doc(hidden)]
pub async fn morph_to<P: Model, T: MorphTo>(
    parent: &P,
    db: &impl Executor,
    columns: [&str; 2],
) -> Result<Option<T>> {
    let Some((alias, id)) = morph_target(parent, columns)? else {
        return Ok(None);
    };
    if let Some(message) = lazy_load::<P>(parent, columns[0].trim_end_matches("_type")) {
        return Err(Error::InvalidQuery(message));
    }
    let models = T::load_morph(db, &alias, vec![id], Nested::default()).await?;
    Ok(models.into_iter().next().map(|(_, model)| model))
}

/// Eager loading of a `morph_to` relation: one query per morph type present.
#[doc(hidden)]
pub async fn load_morph<P: Model, T: MorphTo, E: Executor>(
    db: &E,
    parents: &mut [P],
    nested: Nested,
    columns: [&str; 2],
    field: fn(&mut P) -> &mut Rel<Option<T>>,
) -> Result<()> {
    let mut wanted: Vec<(String, Vec<Value>)> = Vec::new();
    let mut parent_keys = Vec::with_capacity(parents.len());
    let mut sharing: HashMap<(String, String), usize> = HashMap::new();
    for parent in parents.iter() {
        let target = morph_target(parent, columns)?.and_then(|(alias, id)| {
            let key = key_string(std::slice::from_ref(&id))?;
            Some((alias, key, id))
        });
        let Some((alias, key, id)) = target else {
            parent_keys.push(None);
            continue;
        };
        let count = sharing.entry((alias.clone(), key.clone())).or_default();
        *count += 1;
        if *count == 1 {
            match wanted.iter_mut().find(|(a, _)| *a == alias) {
                Some((_, ids)) => ids.push(id),
                None => wanted.push((alias.clone(), vec![id])),
            }
        }
        parent_keys.push(Some((alias, key)));
    }

    let mut found: HashMap<(String, String), T> = HashMap::new();
    for (alias, ids) in wanted {
        for (id, model) in T::load_morph(db, &alias, ids, nested.clone()).await? {
            if let Some(key) = key_string(&[id]) {
                found.insert((alias.clone(), key), model);
            }
        }
    }

    for (parent, key) in parents.iter_mut().zip(parent_keys) {
        let model = key.and_then(|key| take_or_clone(&mut found, &mut sharing, key));
        *field(parent) = Rel::Loaded(model);
    }
    Ok(())
}

/// The pivot table of a `belongs_to_many` relation, from the generated
/// `parent.roles_pivot()`. Keys are the related model's primary keys.
#[must_use]
pub struct Pivot<R> {
    relation: Relation,
    through: Through,
    parent: Vec<Value>,
    related: PhantomData<fn() -> R>,
}

impl<R: Model> Pivot<R> {
    /// # Errors
    ///
    /// [`Error::InvalidQuery`] when the parent has no key yet.
    #[doc(hidden)]
    pub fn new<P: Model>(parent: &P, name: &str) -> Result<Self> {
        let relation = Relation::lookup::<P>(name)?;
        let through = relation
            .through
            .ok_or_else(|| Error::InvalidQuery(format!("relation `{name}` has no pivot table")))?;
        let parent = column_values(parent, relation.local)?;
        if parent.iter().any(Value::is_null) {
            return Err(Error::InvalidQuery(
                "save the parent model before changing its pivot rows".to_owned(),
            ));
        }
        Ok(Self {
            relation,
            through,
            parent,
            related: PhantomData,
        })
    }

    /// Pivot rows of the parent.
    fn rows(&self) -> QueryBuilder {
        let mut query = QueryBuilder::table(self.through.table);
        if let Some((column, value)) = self.through.morph {
            query = query.where_(column, "=", value);
        }
        self.relation
            .remote
            .iter()
            .zip(&self.parent)
            .fold(query, |q, (column, value)| {
                q.where_(*column, "=", value.clone())
            })
    }

    /// Inserts a pivot row per key, with `created_at` / `updated_at` when
    /// the relation has `pivot_timestamps`.
    ///
    /// # Errors
    ///
    /// Database errors, e.g. a duplicate pivot row.
    pub async fn attach(
        &self,
        db: &impl Executor,
        keys: impl IntoIterator<Item = R::Key>,
    ) -> Result<()> {
        self.attach_with(db, keys, Vec::new()).await
    }

    /// As [`attach`](Self::attach), setting the extra pivot columns
    /// `values` on every new row, like Eloquent's `attach($ids, [...])`.
    ///
    /// # Errors
    ///
    /// As [`attach`](Self::attach).
    pub async fn attach_with(
        &self,
        db: &impl Executor,
        keys: impl IntoIterator<Item = R::Key>,
        values: Vec<(&str, Value)>,
    ) -> Result<()> {
        let keys = keys.into_iter().map(R::key_values).collect();
        self.insert(db, keys, values).await
    }

    pub(crate) async fn insert(
        &self,
        db: &impl Executor,
        keys: Vec<Vec<Value>>,
        mut values: Vec<(&str, Value)>,
    ) -> Result<()> {
        if keys.is_empty() {
            return Ok(());
        }
        if let Some([created_at, updated_at]) = self.through.timestamps {
            let now = now();
            values.push((created_at, now.clone()));
            values.push((updated_at, now));
        }
        if let Some((column, value)) = self.through.morph {
            values.push((column, value.into()));
        }
        let (extra_columns, extra): (Vec<&str>, Vec<Value>) = values.into_iter().unzip();
        let columns: Vec<&str> = (self.relation.remote.iter())
            .chain(self.through.through_key)
            .copied()
            .chain(extra_columns)
            .collect();
        let rows = keys
            .into_iter()
            .map(|key| {
                (self.parent.iter().cloned())
                    .chain(key)
                    .chain(extra.iter().cloned())
                    .collect()
            })
            .collect();
        QueryBuilder::table(self.through.table)
            .insert(db, &columns, rows)
            .await?;
        Ok(())
    }

    /// Sets pivot columns `values` (plus `updated_at` with
    /// `pivot_timestamps`) on the pivot row of `key`, like Eloquent's
    /// `updateExistingPivot`, and returns how many rows changed.
    ///
    /// # Errors
    ///
    /// Database errors.
    pub async fn update_existing(
        &self,
        db: &impl Executor,
        key: R::Key,
        mut values: Vec<(&str, Value)>,
    ) -> Result<u64> {
        if let Some([_, updated_at]) = self.through.timestamps {
            values.push((updated_at, now()));
        }
        let query = (self.through.through_key.iter())
            .zip(R::key_values(key))
            .fold(self.rows(), |q, (column, value)| {
                q.where_(*column, "=", value)
            });
        query.update(db, values).await
    }

    /// Deletes the pivot rows of `keys` and returns how many were removed.
    ///
    /// # Errors
    ///
    /// Database errors.
    pub async fn detach(
        &self,
        db: &impl Executor,
        keys: impl IntoIterator<Item = R::Key>,
    ) -> Result<u64> {
        let keys = keys.into_iter().map(R::key_values).collect();
        self.delete(db, keys).await
    }

    /// One statement per [`KEYS_PER_QUERY`] keys, all or nothing.
    async fn delete(&self, db: &impl Executor, keys: Vec<Vec<Value>>) -> Result<u64> {
        let columns: Vec<String> = self
            .through
            .through_key
            .iter()
            .map(|c| (*c).to_owned())
            .collect();
        let mut statements = batches(keys)
            .map(|batch| {
                where_keys(self.rows(), columns.clone(), batch).to_delete_sql(db.dialect())
            })
            .collect::<Result<Vec<_>>>()?;
        let executed = match statements.len() {
            0 => return Ok(0),
            1 => vec![db.execute(statements.remove(0)).await?],
            _ => db.execute_all(statements).await?,
        };
        Ok(executed.iter().map(|e| e.rows_affected).sum())
    }

    /// Deletes every pivot row of the parent.
    ///
    /// # Errors
    ///
    /// Database errors.
    pub async fn detach_all(&self, db: &impl Executor) -> Result<u64> {
        self.rows().delete(db).await
    }

    /// Makes `keys` the parent's only related keys: detaches the others and
    /// attaches the missing ones.
    ///
    /// # Errors
    ///
    /// Database errors.
    pub async fn sync(
        &self,
        db: &impl Executor,
        keys: impl IntoIterator<Item = R::Key>,
    ) -> Result<()> {
        let current = self.current(db).await?;
        let (attach, wanted) = missing(&current, keys.into_iter().map(R::key_values));
        let detach: Vec<Vec<Value>> = current
            .into_iter()
            .filter(|k| key_string(k).is_some_and(|s| !wanted.contains(&s)))
            .collect();
        if !detach.is_empty() {
            self.delete(db, detach).await?;
        }
        self.insert(db, attach, Vec::new()).await
    }

    /// Attaches those of `keys` that are not attached yet and leaves the
    /// others alone, like Eloquent's `syncWithoutDetaching`.
    ///
    /// # Errors
    ///
    /// Database errors.
    pub async fn sync_without_detaching(
        &self,
        db: &impl Executor,
        keys: impl IntoIterator<Item = R::Key>,
    ) -> Result<()> {
        let current = self.current(db).await?;
        let (attach, _) = missing(&current, keys.into_iter().map(R::key_values));
        self.insert(db, attach, Vec::new()).await
    }

    /// Detaches those of `keys` that are attached and attaches the others,
    /// like Eloquent's `toggle`.
    ///
    /// # Errors
    ///
    /// Database errors.
    pub async fn toggle(
        &self,
        db: &impl Executor,
        keys: impl IntoIterator<Item = R::Key>,
    ) -> Result<()> {
        let current = self.current(db).await?;
        let (attach, wanted) = missing(&current, keys.into_iter().map(R::key_values));
        let detach: Vec<Vec<Value>> = current
            .into_iter()
            .filter(|k| key_string(k).is_some_and(|s| wanted.contains(&s)))
            .collect();
        if !detach.is_empty() {
            self.delete(db, detach).await?;
        }
        self.insert(db, attach, Vec::new()).await
    }

    /// Related keys in the parent's pivot rows.
    async fn current(&self, db: &impl Executor) -> Result<Vec<Vec<Value>>> {
        let through = self.through;
        self.rows()
            .select(through.through_key.iter().copied())
            .get(db)
            .await?
            .iter()
            .map(|row| through.through_key.iter().map(|c| row.get(c)).collect())
            .collect()
    }
}

/// Of `keys`, those not in `current` (each once), and every key of `keys` as a key string.
fn missing(
    current: &[Vec<Value>],
    keys: impl Iterator<Item = Vec<Value>>,
) -> (Vec<Vec<Value>>, HashSet<String>) {
    let current: HashSet<String> = current.iter().filter_map(|k| key_string(k)).collect();
    let mut wanted = HashSet::new();
    let mut absent = Vec::new();
    for key in keys {
        let Some(string) = key_string(&key) else {
            continue;
        };
        if !current.contains(&string) && !wanted.contains(&string) {
            absent.push(key);
        }
        wanted.insert(string);
    }
    (absent, wanted)
}

#[cfg(test)]
mod tests {
    use super::*;
    use rust_decimal::Decimal;

    #[test]
    fn keys_match_across_number_types() {
        let decimal = Value::Decimal(Decimal::from(7));
        assert_eq!(key_string(&[Value::I64(7)]), key_string(&[decimal]));
        assert_eq!(key_string(&[Value::U64(7)]), key_string(&[Value::I64(7)]));
        assert_ne!(
            key_string(&[Value::from("a|"), Value::from("b")]),
            key_string(&[Value::from("a"), Value::from("|b")])
        );
        assert_eq!(key_string(&[Value::I64(1), Value::Null]), None);
    }
}
