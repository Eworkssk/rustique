/// Outcome of a statement that returns no rows.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
#[non_exhaustive]
pub struct Executed {
    /// Rows inserted, updated or deleted.
    pub rows_affected: u64,
    /// Key generated by an insert: MySQL's `AUTO_INCREMENT` id, or on Oracle
    /// the value of `RETURNING ... INTO` (see [`Compiled::returning`]).
    pub last_insert_id: Option<u64>,
}

mod sealed {
    pub trait Sealed {}
}

/// An error type whose deadlocks and serialization failures
/// [`Db::transaction_with_retries`] can recognise.
pub trait TransactionError: From<Error> {
    /// Whether running the transaction again may succeed.
    fn is_concurrency_error(&self) -> bool;
}

impl TransactionError for Error {
    fn is_concurrency_error(&self) -> bool {
        Error::is_concurrency_error(self)
    }
}

/// Runs compiled SQL: implemented by [`Db`] and [`Transaction`].
///
/// Query methods take `&impl Executor`, so the same code runs inside or
/// outside a transaction. Sealed: only this crate implements it.
pub trait Executor: Sync + sealed::Sealed {
    /// Dialect that queries must be compiled for.
    fn dialect(&self) -> Dialect;

    /// Runs a query and returns all its rows.
    ///
    /// # Errors
    ///
    /// [`Error::Database`] when the database rejects the query,
    /// [`Error::Decode`] when a column has a type the ORM cannot read.
    fn fetch_all(&self, query: Compiled) -> impl Future<Output = Result<Vec<Row>>> + Send {
        self.fetch_map(query, Ok)
    }

    /// As [`fetch_all`](Self::fetch_all), turning each row into a `T` with
    /// `f` as it arrives, so the rows are never all held at once.
    #[doc(hidden)]
    fn fetch_map<T: Send + 'static>(
        &self,
        query: Compiled,
        f: impl FnMut(Row) -> Result<T> + Send + 'static,
    ) -> impl Future<Output = Result<Vec<T>>> + Send;

    /// Runs a statement that returns no rows.
    ///
    /// # Errors
    ///
    /// [`Error::Database`] when the database rejects the statement.
    fn execute(&self, query: Compiled) -> impl Future<Output = Result<Executed>> + Send;

    /// Runs a query and streams its rows; see [`Cursor`]. Errors arrive
    /// through [`Cursor::next`]. Needs a running tokio runtime.
    fn cursor(&self, query: Compiled) -> Cursor<'_> {
        self.cursor_buffered(query, cursor::BUFFER)
    }

    /// As [`cursor`](Self::cursor), reading up to `buffer` rows ahead.
    fn cursor_buffered(&self, query: Compiled, buffer: usize) -> Cursor<'_>;

    /// Runs `queries` one after another on one connection, all or nothing:
    /// [`Db`] wraps them in a transaction, [`Transaction`] in a savepoint.
    ///
    /// # Errors
    ///
    /// The first statement's error, after undoing the statements before it.
    fn execute_all(
        &self,
        queries: Vec<Compiled>,
    ) -> impl Future<Output = Result<Vec<Executed>>> + Send;

    /// As [`execute_all`](Self::execute_all), for queries returning rows:
    /// the rows of each query.
    #[doc(hidden)]
    fn fetch_each(
        &self,
        queries: Vec<Compiled>,
    ) -> impl Future<Output = Result<Vec<Vec<Row>>>> + Send;

    /// The next `count` values of the Oracle sequence `sequence` (`"seq"` or
    /// `"schema.seq"`), in one round trip, for keys an application assigns
    /// itself before inserting, such as parent and child rows inserted
    /// together. The values are unique but need not be consecutive or in
    /// order (sequence caching, RAC). Always runs on the main database,
    /// never a read replica. A `count` of 0 returns no values without a query.
    ///
    /// ```no_run
    /// # use rustique::prelude::*;
    /// # async fn run(db: &Db) -> rustique::Result<()> {
    /// let ids = db.next_sequence_values("orders_seq", 500).await?;
    /// # Ok(()) }
    /// ```
    ///
    /// # Errors
    ///
    /// [`Error::Unsupported`] on MySQL, which has no sequences;
    /// [`Error::Database`] when the sequence does not exist.
    fn next_sequence_values(
        &self,
        sequence: &str,
        count: usize,
    ) -> impl Future<Output = Result<Vec<i64>>> + Send {
        let compiled = grammar::next_sequence_values(self.dialect(), sequence, count);
        async move {
            let query = compiled?;
            if count == 0 {
                return Ok(Vec::new());
            }
            // `NEXTVAL` writes: never on a replica.
            let primary = self.erase().on_writer();
            primary.fetch_map(query, |row| row.get("id")).await
        }
    }

    /// This executor as an [`AnyExecutor`].
    #[doc(hidden)]
    fn erase(&self) -> AnyExecutor<'_>;

    /// Runs raw SQL returning rows, like Laravel's `DB::select`. `?` marks bindings.
    ///
    /// # Errors
    ///
    /// As [`fetch_all`](Self::fetch_all), plus [`Error::InvalidQuery`] when the
    /// number of `?` and bindings differ.
    fn select(
        &self,
        sql: &str,
        binds: impl IntoIterator<Item = Value>,
    ) -> impl Future<Output = Result<Vec<Row>>> + Send {
        let compiled = grammar::raw(self.dialect(), sql, binds);
        async move { self.fetch_all(compiled?).await }
    }

    /// Runs raw SQL returning no rows, like Laravel's `DB::statement`. `?` marks bindings.
    ///
    /// # Errors
    ///
    /// As [`execute`](Self::execute), plus [`Error::InvalidQuery`] when the
    /// number of `?` and bindings differ.
    fn statement(
        &self,
        sql: &str,
        binds: impl IntoIterator<Item = Value>,
    ) -> impl Future<Output = Result<Executed>> + Send {
        let compiled = grammar::raw(self.dialect(), sql, binds);
        async move { self.execute(compiled?).await }
    }
}

/// A `&Db` or a `&Transaction`, as one type: what factory callbacks such as
/// [`Factory::after_creating`](crate::Factory::after_creating) receive,
/// since a stored closure cannot be generic over `impl Executor`. Use it
/// like the executor it wraps.
#[derive(Debug, Clone, Copy)]
pub struct AnyExecutor<'a>(AnyInner<'a>);

#[derive(Debug, Clone, Copy)]
enum AnyInner<'a> {
    Db(&'a Db),
    /// A [`Db`] whose reads go to the main database, not its replicas.
    Writer(&'a Db),
    Transaction(&'a Transaction),
}

impl<'a> AnyExecutor<'a> {
    /// This executor with every query on the main database, never a read
    /// replica: for reads that must see the latest writes.
    pub(crate) fn on_writer(self) -> Self {
        match self.0 {
            AnyInner::Db(db) => Self(AnyInner::Writer(db)),
            _ => self,
        }
    }
}

impl<'a> From<&'a Db> for AnyExecutor<'a> {
    fn from(db: &'a Db) -> Self {
        Self(AnyInner::Db(db))
    }
}

impl<'a> From<&'a Transaction> for AnyExecutor<'a> {
    fn from(tx: &'a Transaction) -> Self {
        Self(AnyInner::Transaction(tx))
    }
}

impl sealed::Sealed for AnyExecutor<'_> {}

impl Executor for AnyExecutor<'_> {
    fn dialect(&self) -> Dialect {
        match self.0 {
            AnyInner::Db(db) | AnyInner::Writer(db) => db.dialect(),
            AnyInner::Transaction(tx) => tx.dialect(),
        }
    }

    async fn fetch_map<T: Send + 'static>(
        &self,
        query: Compiled,
        f: impl FnMut(Row) -> Result<T> + Send + 'static,
    ) -> Result<Vec<T>> {
        match self.0 {
            AnyInner::Db(db) => db.fetch_map(query, f).await,
            AnyInner::Writer(db) => db.fetch_from(&db.pool, query, false, f).await,
            AnyInner::Transaction(tx) => tx.fetch_map(query, f).await,
        }
    }

    async fn execute(&self, query: Compiled) -> Result<Executed> {
        match self.0 {
            AnyInner::Db(db) | AnyInner::Writer(db) => db.execute(query).await,
            AnyInner::Transaction(tx) => tx.execute(query).await,
        }
    }

    // As `Db`'s: hooks and factory callbacks get an `AnyExecutor`.
    fn select(
        &self,
        sql: &str,
        binds: impl IntoIterator<Item = Value>,
    ) -> impl Future<Output = Result<Vec<Row>>> + Send {
        if let AnyInner::Transaction(tx) = self.0 {
            tx.note_raw(sql);
        }
        let compiled = grammar::raw(self.dialect(), sql, binds);
        async move {
            let query = compiled?;
            match self.0 {
                AnyInner::Db(db) => db.fetch_from(db.pool_for(&query), query, true, Ok).await,
                AnyInner::Writer(db) => db.fetch_from(&db.pool, query, true, Ok).await,
                AnyInner::Transaction(tx) => tx.fetch_all(query).await,
            }
        }
    }

    fn statement(
        &self,
        sql: &str,
        binds: impl IntoIterator<Item = Value>,
    ) -> impl Future<Output = Result<Executed>> + Send {
        if let AnyInner::Transaction(tx) = self.0 {
            tx.note_raw(sql);
        }
        let compiled = grammar::raw(self.dialect(), sql, binds);
        async move {
            match self.0 {
                AnyInner::Db(db) | AnyInner::Writer(db) => db.execute_raw(compiled?, true).await,
                AnyInner::Transaction(tx) => tx.execute(compiled?).await,
            }
        }
    }

    fn cursor_buffered(&self, query: Compiled, buffer: usize) -> Cursor<'_> {
        match self.0 {
            AnyInner::Db(db) => db.cursor_buffered(query, buffer),
            AnyInner::Writer(db) => db.cursor_from(&db.pool, query, buffer),
            AnyInner::Transaction(tx) => tx.cursor_buffered(query, buffer),
        }
    }

    async fn execute_all(&self, queries: Vec<Compiled>) -> Result<Vec<Executed>> {
        match self.0 {
            AnyInner::Db(db) | AnyInner::Writer(db) => db.execute_all(queries).await,
            AnyInner::Transaction(tx) => tx.execute_all(queries).await,
        }
    }

    async fn fetch_each(&self, queries: Vec<Compiled>) -> Result<Vec<Vec<Row>>> {
        match self.0 {
            AnyInner::Db(db) | AnyInner::Writer(db) => db.fetch_each(queries).await,
            AnyInner::Transaction(tx) => tx.fetch_each(queries).await,
        }
    }

    fn erase(&self) -> AnyExecutor<'_> {
        *self
    }
}

/// A connection pool and the entry point of the ORM. Cheap to clone.
///
/// Each query outside a transaction borrows a pooled connection for its
/// duration and runs in autocommit mode.
///
/// Every statement is logged through `tracing` under the target
/// `rustique::query`: its SQL, duration and row count at `DEBUG`, its bindings at
/// `TRACE`.
/// It also runs in an `INFO` span `rustique.query` with OpenTelemetry's database
/// attributes, which `tracing-opentelemetry` exports as a client span under
/// the caller's current span (an APM transaction, for example).
///
/// With read replicas ([`DbBuilder::read_url`]), plain `SELECT`s outside
/// transactions go to the replicas in turn; writes, locking reads
/// (`FOR UPDATE` / `FOR SHARE`), transactions, schema introspection and
/// migrations use the main database.
#[derive(Clone)]
pub struct Db {
    pool: Pool,
    /// Read replicas; empty without any, or after [`Db::write`].
    read: Arc<[Pool]>,
    /// Round-robin position over `read`, shared by clones.
    next_read: Arc<AtomicUsize>,
    /// See [`DbBuilder::sticky`].
    sticky: bool,
}

tokio::task_local! {
    /// Whether a sticky [`Db`] wrote inside the current [`Db::sticky_scope`].
    static WROTE: Arc<AtomicBool>;
}

#[derive(Clone)]
enum Pool {
    #[cfg(feature = "mysql")]
    MySql(mysql::Pool),
    #[cfg(feature = "oracle")]
    Oracle(oracle::Pool),
}

impl Pool {
    /// Connects: fails fast on bad credentials or an unreachable host.
    async fn open(&self) -> Result<()> {
        match self {
            #[cfg(feature = "mysql")]
            Self::MySql(pool) => mysql::checkout(pool).await.map(drop),
            #[cfg(feature = "oracle")]
            Self::Oracle(pool) => pool.open().await,
        }
    }

    /// The database this pool connects to, for statement spans.
    fn peer(&self) -> &Arc<log::Peer> {
        match self {
            #[cfg(feature = "mysql")]
            Self::MySql(pool) => &pool.peer,
            #[cfg(feature = "oracle")]
            Self::Oracle(pool) => &pool.peer,
        }
    }
}

impl Db {
    /// Connects to the database at `url` and checks that it answers.
    ///
    /// - MySQL: `mysql://user:password@host:3306/database`, with any option
    ///   `mysql_async` accepts in the query string (`pool_max`, ...). TLS:
    ///   `?require_ssl=true` (needs the default `mysql-tls` feature).
    ///   Pooled connections are not reset between queries, so session state
    ///   set outside a transaction (`SET ...`, temporary tables) stays on the
    ///   connection; `?reset_connection=true` resets them, at the cost of a
    ///   round trip and re-preparing statements.
    /// - Oracle: `oracle://user:password@host:1521/service_name`, or any
    ///   EZConnect Plus address with a protocol, such as
    ///   `oracle://user:password@tcps://host:2484/service_name?wallet_location=/path`
    ///   for TLS. Needs Oracle Instant Client installed. Pool of 10 connections.
    ///
    /// Queries wait up to 30 seconds for a pooled connection. Percent-encode
    /// special characters in the user and password. [`Db::builder`] sets pool
    /// size, timeouts, session setup and MySQL certificates in code, and
    /// [`DbBuilder::connect_lazy`] creates a pool that connects on first use.
    ///
    /// # Errors
    ///
    /// [`Error::Config`] for a malformed URL or a driver that is not compiled
    /// in, [`Error::Database`] when the connection fails.
    pub async fn connect(url: &str) -> Result<Self> {
        Self::builder(url).connect().await
    }

    /// Settings for a pool at `url` (see [`Db::connect`]): pool size,
    /// timeouts, MySQL TLS certificates. Finish with [`DbBuilder::connect`].
    pub fn builder(url: &str) -> DbBuilder {
        DbBuilder::new(url)
    }

    /// A pool for `url` that has not connected yet.
    fn open(url: &str, mut config: options::PoolConfig) -> Result<Self> {
        let scheme = url.split_once("://").map_or("", |(scheme, _)| scheme);
        if let Some(zone) = &config.timezone {
            // Inlined into SQL: session setup takes no bindings.
            if zone.contains(['\'', '\\']) {
                return Err(Error::Config(format!("invalid time zone `{zone}`")));
            }
            let sql = match scheme {
                "oracle" => format!("ALTER SESSION SET TIME_ZONE = '{zone}'"),
                _ => format!("SET time_zone = '{zone}'"),
            };
            config.session_setup.insert(0, sql);
        }
        let pool = match scheme {
            #[cfg(feature = "mysql")]
            "mysql" => Pool::MySql(mysql::pool(url, config)?),
            #[cfg(feature = "oracle")]
            "oracle" => Pool::Oracle(oracle::Pool::new(url, config)?),
            _ => {
                return Err(Error::Config(format!(
                    "unsupported URL scheme `{scheme}://`; enabled drivers: {}",
                    ENABLED_DRIVERS.join(", ")
                )));
            }
        };
        Ok(Self {
            pool,
            read: Arc::new([]),
            next_read: Arc::new(AtomicUsize::new(0)),
            sticky: false,
        })
    }

    /// Runs `f` as one sticky scope, such as a web request, like Laravel's
    /// `sticky` option for a request: once a [sticky](DbBuilder::sticky)
    /// `Db` writes inside it, its plain reads go to the primary until the
    /// scope ends, so they see that write. Outside a scope, `sticky` has no
    /// effect. A nested scope shares the outer one's state.
    // shortcut: the flag is task-local, so tasks spawned inside the scope do
    // not share it, and one write pins reads of every sticky `Db` in the
    // scope; wrap spawned work in its own scope if it must stick too.
    pub async fn sticky_scope<F: Future>(f: F) -> F::Output {
        let wrote = WROTE.try_with(Arc::clone).unwrap_or_default();
        WROTE.scope(wrote, f).await
    }

    /// Marks the current sticky scope as written, for a sticky `Db`.
    fn wrote(&self) {
        if self.sticky {
            let _ = WROTE.try_with(|wrote| wrote.store(true, Ordering::Relaxed));
        }
    }

    /// This pool without its read replicas: every query on the main
    /// database, like Laravel's `useWritePdo()`. Use it where a read must
    /// see a write made just before, which a lagging replica may not have yet.
    /// Cheap; without replicas it is a plain clone.
    #[must_use]
    pub fn write(&self) -> Self {
        Self {
            read: Arc::new([]),
            ..self.clone()
        }
    }

    /// The pool a query runs on: a replica for plain reads, if there are any.
    fn pool_for(&self, query: &Compiled) -> &Pool {
        let stuck = self.sticky
            && WROTE
                .try_with(|w| w.load(Ordering::Relaxed))
                .unwrap_or(false);
        if self.read.is_empty() || stuck || !is_plain_read(query) {
            return &self.pool;
        }
        let next = self.next_read.fetch_add(1, Ordering::Relaxed);
        &self.read[next % self.read.len()]
    }

    /// `raw`: the query is raw SQL from [`Executor::select`]; see `mysql::checkout_for`.
    /// Rows go through `f` as in [`Executor::fetch_map`].
    async fn fetch_from<T: Send + 'static>(
        &self,
        pool: &Pool,
        query: Compiled,
        raw: bool,
        f: impl FnMut(Row) -> Result<T> + Send + 'static,
    ) -> Result<Vec<T>> {
        log::logged(pool.peer(), query, |query| async move {
            match pool {
                #[cfg(feature = "mysql")]
                Pool::MySql(pool) => {
                    mysql::checkout_for(pool, raw)
                        .await?
                        .fetch_all(query, f)
                        .await
                }
                #[cfg(feature = "oracle")]
                Pool::Oracle(pool) => pool.fetch_all(query, raw, f).await,
            }
        })
        .await
    }

    /// [`Executor::execute`]; `raw` as for [`fetch_from`](Self::fetch_from).
    async fn execute_raw(&self, query: Compiled, raw: bool) -> Result<Executed> {
        self.wrote();
        log::logged(self.pool.peer(), query, |query| async move {
            match &self.pool {
                #[cfg(feature = "mysql")]
                Pool::MySql(pool) => mysql::checkout_for(pool, raw).await?.execute(query).await,
                #[cfg(feature = "oracle")]
                Pool::Oracle(pool) => pool.execute(query, raw).await,
            }
        })
        .await
    }

    fn cursor_from(&self, pool: &Pool, query: Compiled, buffer: usize) -> Cursor<'_> {
        // Entered while the driver spawns its task, which `Cursor` instruments with it.
        let _span = log::statement(pool.peer(), &query.sql).entered();
        match pool {
            #[cfg(feature = "mysql")]
            Pool::MySql(pool) => mysql::cursor(pool, query, buffer),
            #[cfg(feature = "oracle")]
            Pool::Oracle(pool) => pool.cursor(query, buffer),
        }
    }

    /// Makes this pool the process-wide one returned by [`Db::global`].
    ///
    /// # Errors
    ///
    /// [`Error::Config`] when a global pool is already set.
    pub fn set_global(self) -> Result<()> {
        GLOBAL
            .set(self)
            .map_err(|_| Error::Config("global Db is already set".into()))
    }

    /// The pool set with [`Db::set_global`], like Laravel's `DB` facade:
    ///
    /// ```no_run
    /// # use rustique::prelude::*;
    /// # async fn run() -> rustique::Result<()> {
    /// Db::connect("mysql://user:password@localhost/app").await?.set_global()?;
    /// let rows = Db::global().select("SELECT * FROM users WHERE id = ?", [1.into()]).await?;
    /// let users = QueryBuilder::table("users").get(Db::global()).await?;
    /// # Ok(())
    /// # }
    /// ```
    ///
    /// # Panics
    ///
    /// When no global pool is set.
    pub fn global() -> &'static Self {
        GLOBAL
            .get()
            .expect("no global Db; call `Db::set_global` first")
    }

    /// Starts a transaction on a dedicated connection.
    ///
    /// # Errors
    ///
    /// [`Error::Database`] when no connection is available or `BEGIN` fails.
    pub async fn begin(&self) -> Result<Transaction> {
        self.wrote(); // a transaction may write
        let conn = match &self.pool {
            #[cfg(feature = "mysql")]
            Pool::MySql(pool) => transaction::Conn::MySql(mysql::begin(pool).await?),
            #[cfg(feature = "oracle")]
            Pool::Oracle(pool) => transaction::Conn::Oracle(pool.begin().await?),
        };
        Ok(Transaction::new(conn, Arc::clone(self.pool.peer())))
    }

    /// Runs `f` in a transaction: commits when it returns `Ok`, rolls back
    /// when it returns `Err` or panics. Like Laravel's `DB::transaction`.
    ///
    /// The call stays `Send` (for `tokio::spawn` and web handlers) when the
    /// closure's future is. Any error type converting from [`Error`] works,
    /// so a business rule can abort the transaction:
    ///
    /// ```no_run
    /// # use rustique::prelude::*;
    /// # async fn run(db: Db) -> rustique::Result<()> {
    /// let id = db
    ///     .transaction(async |tx| {
    ///         tx.statement("UPDATE accounts SET balance = balance - 10 WHERE id = ?", [1.into()]).await?;
    ///         let done = tx.statement("INSERT INTO payments (amount) VALUES (?)", [10.into()]).await?;
    ///         Ok::<_, rustique::Error>(done.last_insert_id)
    ///     })
    ///     .await?;
    /// # Ok(()) }
    /// ```
    ///
    /// # Errors
    ///
    /// The closure's error, or [`Error::Database`] when `BEGIN` or `COMMIT`
    /// fails. A failing `ROLLBACK` is logged; the closure's error is returned.
    pub async fn transaction<T, E, F>(&self, f: F) -> Result<T, E>
    where
        F: AsyncFnOnce(&Transaction) -> Result<T, E>,
        E: From<Error>,
    {
        let tx = self.begin().await?;
        match f(&tx).await {
            Ok(value) => {
                tx.commit().await?;
                Ok(value)
            }
            Err(e) => {
                if let Err(rollback) = tx.rollback().await {
                    tracing::warn!(target: "rustique::query", error = %rollback, "rollback failed");
                }
                Err(e)
            }
        }
    }

    /// As [`transaction`](Self::transaction), but runs `f` again in a new
    /// transaction, up to `attempts` times in all, when it fails with a
    /// deadlock or serialization failure (see
    /// [`Error::is_concurrency_error`]), like Laravel's
    /// `DB::transaction($fn, $attempts)`. Other errors return at once.
    ///
    /// The error type tells retryable errors apart through
    /// [`TransactionError`], implemented for [`Error`]; implement it for an
    /// application error type that wraps [`Error`].
    ///
    /// Where the call must be `Send` (`tokio::spawn`, web handlers), pass an
    /// `async move |tx| { ... }` closure that owns its captures: rustc cannot
    /// yet prove a borrowing `AsyncFnMut` closure's future `Send`.
    ///
    /// # Errors
    ///
    /// As [`transaction`](Self::transaction), from the last attempt.
    pub async fn transaction_with_retries<T, E, F>(&self, attempts: u32, mut f: F) -> Result<T, E>
    where
        F: AsyncFnMut(&Transaction) -> Result<T, E>,
        E: TransactionError,
    {
        let mut attempt = 1;
        loop {
            match self.transaction(async |tx| f(tx).await).await {
                Err(e) if attempt < attempts && e.is_concurrency_error() => {
                    tracing::debug!(target: "rustique::query", attempt, "retrying transaction after a concurrency error");
                    attempt += 1;
                }
                result => return result,
            }
        }
    }

    /// Runs `f` in a transaction that is always rolled back, and returns
    /// what `f` returned. Meant for tests: each test sees its own writes,
    /// and the database is left as it was.
    ///
    /// ```no_run
    /// # use rustique::prelude::*;
    /// # async fn run(db: Db) -> rustique::Result<()> {
    /// db.rollback_after(async |tx| {
    ///     tx.statement("DELETE FROM users", []).await?;
    ///     assert_eq!(QueryBuilder::table("users").count(tx).await?, 0);
    ///     Ok::<_, rustique::Error>(())
    /// })
    /// .await?;
    /// # Ok(()) }
    /// ```
    ///
    /// DDL commits implicitly on both databases, so schema changes inside
    /// `f` are not undone.
    ///
    /// # Errors
    ///
    /// The closure's error, or [`Error::Database`] when `BEGIN` or `ROLLBACK` fails.
    pub async fn rollback_after<T, E, F>(&self, f: F) -> Result<T, E>
    where
        F: AsyncFnOnce(&Transaction) -> Result<T, E>,
        E: From<Error>,
    {
        let tx = self.begin().await?;
        let result = f(&tx).await;
        tx.rollback().await?;
        result
    }

    /// Closes every pooled connection. Clones of this `Db` stop working.
    ///
    /// # Errors
    ///
    /// [`Error::Database`] when the driver fails to close the pool.
    pub async fn disconnect(self) -> Result<()> {
        for pool in self.read.iter().chain([&self.pool]) {
            match pool.clone() {
                #[cfg(feature = "mysql")]
                Pool::MySql(pool) => mysql::disconnect(pool).await?,
                #[cfg(feature = "oracle")]
                Pool::Oracle(pool) => pool.close().await?,
            }
        }
        Ok(())
    }
}

/// Whether `query` only reads and may run on a replica: a `SELECT` without
/// row locks and out binds. Anything else, `WITH` and `CALL` included, goes
/// to the main database.
fn is_plain_read(query: &Compiled) -> bool {
    // Raw SQL may break lines anywhere: `...\nFOR UPDATE` locks too.
    let sql = query.sql.split_whitespace().collect::<Vec<_>>().join(" ");
    let sql = sql.to_ascii_uppercase();
    query.returning == 0
        && query.batch.is_none()
        && sql.starts_with("SELECT")
        && !sql.contains(" FOR UPDATE")
        && !sql.contains(" FOR SHARE")
        && !sql.contains(" LOCK IN SHARE MODE")
}

