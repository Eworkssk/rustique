impl fmt::Debug for Db {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Db")
            .field("dialect", &self.dialect())
            .finish_non_exhaustive()
    }
}

impl sealed::Sealed for Db {}

impl Executor for Db {
    fn dialect(&self) -> Dialect {
        match self.pool {
            #[cfg(feature = "mysql")]
            Pool::MySql(_) => Dialect::MySql,
            #[cfg(feature = "oracle")]
            Pool::Oracle(_) => Dialect::Oracle,
        }
    }

    async fn fetch_map<T: Send + 'static>(
        &self,
        query: Compiled,
        f: impl FnMut(Row) -> Result<T> + Send + 'static,
    ) -> Result<Vec<T>> {
        self.fetch_from(self.pool_for(&query), query, false, f)
            .await
    }

    async fn execute(&self, query: Compiled) -> Result<Executed> {
        self.execute_raw(query, false).await
    }

    fn select(
        &self,
        sql: &str,
        binds: impl IntoIterator<Item = Value>,
    ) -> impl Future<Output = Result<Vec<Row>>> + Send {
        let compiled = grammar::raw(self.dialect(), sql, binds);
        async move {
            let query = compiled?;
            self.fetch_from(self.pool_for(&query), query, true, Ok)
                .await
        }
    }

    fn statement(
        &self,
        sql: &str,
        binds: impl IntoIterator<Item = Value>,
    ) -> impl Future<Output = Result<Executed>> + Send {
        let compiled = grammar::raw(self.dialect(), sql, binds);
        async move { self.execute_raw(compiled?, true).await }
    }

    fn cursor_buffered(&self, query: Compiled, buffer: usize) -> Cursor<'_> {
        self.cursor_from(self.pool_for(&query), query, buffer)
    }

    async fn execute_all(&self, queries: Vec<Compiled>) -> Result<Vec<Executed>> {
        let tx = self.begin().await?;
        let mut results = Vec::with_capacity(queries.len());
        for query in queries {
            results.push(tx.execute(query).await?); // dropping `tx` rolls back
        }
        tx.commit().await?;
        Ok(results)
    }

    async fn fetch_each(&self, queries: Vec<Compiled>) -> Result<Vec<Vec<Row>>> {
        let tx = self.begin().await?;
        let mut results = Vec::with_capacity(queries.len());
        for query in queries {
            results.push(tx.fetch_all(query).await?); // dropping `tx` rolls back
        }
        tx.commit().await?;
        Ok(results)
    }

    fn erase(&self) -> AnyExecutor<'_> {
        self.into()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn plain_reads() {
        let query = |sql: &str, returning| Compiled {
            sql: sql.to_owned(),
            binds: Vec::new(),
            batch: None,
            returning,
        };
        assert!(is_plain_read(&query(" select * from t", 0)));
        assert!(!is_plain_read(&query("SELECT * FROM t FOR UPDATE", 0)));
        assert!(!is_plain_read(&query(
            "SELECT * FROM t FOR SHARE SKIP LOCKED",
            0
        )));
        assert!(!is_plain_read(&query("SELECT * FROM t\nFOR\tUPDATE", 0)));
        assert!(!is_plain_read(&query(
            "SELECT * FROM t LOCK IN SHARE MODE",
            0
        )));
        assert!(!is_plain_read(&query("INSERT INTO t VALUES (1)", 0)));
        assert!(!is_plain_read(&query("BEGIN INSERT ... END;", 2)));
        assert!(!is_plain_read(&query(
            "WITH x AS (SELECT 1) SELECT * FROM x",
            0
        )));
    }
}
