use rustique::{Blueprint, Dialect};

#[track_caller]
fn assert_ddl(blueprint: &Blueprint, mysql: &[&str], oracle: &[&str]) {
    assert_eq!(blueprint.to_sql(Dialect::MySql).unwrap(), mysql, "MySQL");
    assert_eq!(blueprint.to_sql(Dialect::Oracle).unwrap(), oracle, "Oracle");
}

#[test]
fn create_table_with_every_column_type() {
    let mut t = Blueprint::create("items");
    t.id();
    t.big_integer("views");
    t.integer("stock").unsigned();
    t.small_integer("rank").nullable();
    t.boolean("active").default(true);
    t.string("name", 100).default("it's");
    t.char("code", 3);
    t.text("body").nullable();
    t.long_text("log").nullable();
    t.double("ratio");
    t.decimal("price", 10, 2).default(0);
    t.date("born").nullable();
    t.datetime("seen_at").nullable();
    t.json("data").nullable();
    t.binary("blob").nullable();
    t.uuid("uid");

    assert_ddl(
        &t,
        &["CREATE TABLE `items` (\
            `id` BIGINT UNSIGNED AUTO_INCREMENT NOT NULL PRIMARY KEY, \
            `views` BIGINT NOT NULL, \
            `stock` INT UNSIGNED NOT NULL, \
            `rank` SMALLINT, \
            `active` TINYINT(1) DEFAULT 1 NOT NULL, \
            `name` VARCHAR(100) DEFAULT 'it''s' NOT NULL, \
            `code` CHAR(3) NOT NULL, \
            `body` TEXT, \
            `log` LONGTEXT, \
            `ratio` DOUBLE NOT NULL, \
            `price` DECIMAL(10, 2) DEFAULT 0 NOT NULL, \
            `born` DATE, \
            `seen_at` DATETIME(6), \
            `data` JSON, \
            `blob` LONGBLOB, \
            `uid` CHAR(36) NOT NULL)"],
        &[
            r#"CREATE TABLE "ITEMS" ("ID" NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "VIEWS" NUMBER(19) NOT NULL, "STOCK" NUMBER(10) NOT NULL, "RANK" NUMBER(5), "ACTIVE" NUMBER(1) DEFAULT 1 NOT NULL CHECK ("ACTIVE" IN (0, 1)), "NAME" VARCHAR2(100 CHAR) DEFAULT 'it''s' NOT NULL, "CODE" CHAR(3 CHAR) NOT NULL, "BODY" CLOB, "LOG" CLOB, "RATIO" BINARY_DOUBLE NOT NULL, "PRICE" NUMBER(10, 2) DEFAULT 0 NOT NULL, "BORN" DATE, "SEEN_AT" TIMESTAMP(6), "DATA" CLOB CHECK ("DATA" IS JSON), "BLOB" BLOB, "UID" CHAR(36) NOT NULL)"#,
        ],
    );
}

#[test]
fn indexes_and_foreign_keys_follow_create_table() {
    let mut t = Blueprint::create("posts");
    t.id();
    t.foreign_id("user_id")
        .constrained("users")
        .cascade_on_delete();
    t.string("slug", 50).unique();
    t.string("title", 50).index();
    t.timestamps();
    t.index(&["user_id", "created_at"]).name("posts_recent");

    assert_ddl(
        &t,
        &[
            "CREATE TABLE `posts` (\
                `id` BIGINT UNSIGNED AUTO_INCREMENT NOT NULL PRIMARY KEY, \
                `user_id` BIGINT UNSIGNED NOT NULL, \
                `slug` VARCHAR(50) NOT NULL, \
                `title` VARCHAR(50) NOT NULL, \
                `created_at` DATETIME(6), \
                `updated_at` DATETIME(6))",
            "ALTER TABLE `posts` ADD CONSTRAINT `posts_user_id_foreign` \
                FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE",
            "CREATE UNIQUE INDEX `posts_slug_unique` ON `posts` (`slug`)",
            "CREATE INDEX `posts_title_index` ON `posts` (`title`)",
            "CREATE INDEX `posts_recent` ON `posts` (`user_id`, `created_at`)",
        ],
        &[
            r#"CREATE TABLE "POSTS" ("ID" NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY, "USER_ID" NUMBER(19) NOT NULL, "SLUG" VARCHAR2(50 CHAR) NOT NULL, "TITLE" VARCHAR2(50 CHAR) NOT NULL, "CREATED_AT" TIMESTAMP(6), "UPDATED_AT" TIMESTAMP(6))"#,
            r#"ALTER TABLE "POSTS" ADD CONSTRAINT "POSTS_USER_ID_FOREIGN" FOREIGN KEY ("USER_ID") REFERENCES "USERS" ("ID") ON DELETE CASCADE"#,
            r#"CREATE UNIQUE INDEX "POSTS_SLUG_UNIQUE" ON "POSTS" ("SLUG")"#,
            r#"CREATE INDEX "POSTS_TITLE_INDEX" ON "POSTS" ("TITLE")"#,
            r#"CREATE INDEX "POSTS_RECENT" ON "POSTS" ("USER_ID", "CREATED_AT")"#,
        ],
    );
}

#[test]
fn composite_primary_and_foreign_keys() {
    let mut t = Blueprint::create("lines");
    t.integer("order_id");
    t.integer("line_no");
    t.integer("part_id").nullable();
    t.primary(&["order_id", "line_no"]);
    t.foreign(&["part_id"], "parts", &["id"]).null_on_delete();

    assert_ddl(
        &t,
        &[
            "CREATE TABLE `lines` (`order_id` INT NOT NULL, `line_no` INT NOT NULL, \
                `part_id` INT, PRIMARY KEY (`order_id`, `line_no`))",
            "ALTER TABLE `lines` ADD CONSTRAINT `lines_part_id_foreign` \
                FOREIGN KEY (`part_id`) REFERENCES `parts` (`id`) ON DELETE SET NULL",
        ],
        &[
            r#"CREATE TABLE "LINES" ("ORDER_ID" NUMBER(10) NOT NULL, "LINE_NO" NUMBER(10) NOT NULL, "PART_ID" NUMBER(10), PRIMARY KEY ("ORDER_ID", "LINE_NO"))"#,
            r#"ALTER TABLE "LINES" ADD CONSTRAINT "LINES_PART_ID_FOREIGN" FOREIGN KEY ("PART_ID") REFERENCES "PARTS" ("ID") ON DELETE SET NULL"#,
        ],
    );
}

#[test]
fn alter_table_adds_columns_then_runs_commands() {
    let mut t = Blueprint::alter("users");
    t.string("nick", 20).nullable().unique();
    t.drop_column("legacy");
    t.rename_column("mail", "email");
    t.drop_index("users_name_index");
    t.drop_foreign("users_team_id_foreign");

    assert_ddl(
        &t,
        &[
            "ALTER TABLE `users` ADD `nick` VARCHAR(20)",
            "CREATE UNIQUE INDEX `users_nick_unique` ON `users` (`nick`)",
            "ALTER TABLE `users` DROP COLUMN `legacy`",
            "ALTER TABLE `users` RENAME COLUMN `mail` TO `email`",
            "DROP INDEX `users_name_index` ON `users`",
            "ALTER TABLE `users` DROP FOREIGN KEY `users_team_id_foreign`",
        ],
        &[
            r#"ALTER TABLE "USERS" ADD "NICK" VARCHAR2(20 CHAR)"#,
            r#"CREATE UNIQUE INDEX "USERS_NICK_UNIQUE" ON "USERS" ("NICK")"#,
            r#"ALTER TABLE "USERS" DROP COLUMN "LEGACY""#,
            r#"ALTER TABLE "USERS" RENAME COLUMN "MAIL" TO "EMAIL""#,
            r#"DROP INDEX "USERS_NAME_INDEX""#,
            r#"ALTER TABLE "USERS" DROP CONSTRAINT "USERS_TEAM_ID_FOREIGN""#,
        ],
    );
}

#[test]
fn default_literals() {
    let date = chrono::NaiveDate::from_ymd_opt(2026, 1, 2).unwrap();
    let mut t = Blueprint::alter("t");
    t.date("d").default(date);
    t.datetime("dt").default(date.and_hms_opt(3, 4, 5).unwrap());
    t.text("note").default(r"a\b");
    t.decimal("n", 5, 1)
        .nullable()
        .default(rustique::Value::Null);

    assert_ddl(
        &t,
        &[
            "ALTER TABLE `t` ADD `d` DATE DEFAULT '2026-01-02' NOT NULL",
            "ALTER TABLE `t` ADD `dt` DATETIME(6) DEFAULT '2026-01-02 03:04:05.000000' NOT NULL",
            r"ALTER TABLE `t` ADD `note` TEXT DEFAULT ('a\\b') NOT NULL",
            "ALTER TABLE `t` ADD `n` DECIMAL(5, 1) DEFAULT NULL",
        ],
        &[
            r#"ALTER TABLE "T" ADD "D" DATE DEFAULT DATE '2026-01-02' NOT NULL"#,
            r#"ALTER TABLE "T" ADD "DT" TIMESTAMP(6) DEFAULT TIMESTAMP '2026-01-02 03:04:05.000000' NOT NULL"#,
            r#"ALTER TABLE "T" ADD "NOTE" CLOB DEFAULT 'a\b' NOT NULL"#,
            r#"ALTER TABLE "T" ADD "N" NUMBER(5, 1) DEFAULT NULL"#,
        ],
    );
}

#[test]
fn invalid_blueprints() {
    let mut t = Blueprint::create("t");
    t.binary("b").default(vec![1_u8]);
    let error = t.to_sql(Dialect::MySql).unwrap_err().to_string();
    assert!(
        error.contains("bytes cannot be a column default"),
        "{error}"
    );

    let mut t = Blueprint::create("t");
    t.foreign_id("user_id").cascade_on_delete();
    let error = t.to_sql(Dialect::Oracle).unwrap_err().to_string();
    assert!(error.contains("call `constrained` first"), "{error}");
}

#[test]
fn change_modifies_existing_columns() {
    let mut t = Blueprint::alter("users");
    t.string("name", 100).nullable().default("n/a").change();
    t.integer("age").change();
    assert_ddl(
        &t,
        &[
            "ALTER TABLE `users` MODIFY `name` VARCHAR(100) DEFAULT 'n/a'",
            "ALTER TABLE `users` MODIFY `age` INT NOT NULL",
        ],
        &[
            "DECLARE n VARCHAR2(1); BEGIN EXECUTE IMMEDIATE 'ALTER TABLE \"USERS\" MODIFY (\"NAME\" VARCHAR2(100 CHAR) DEFAULT ''n/a'')'; \
             SELECT nullable INTO n FROM all_tab_columns WHERE owner = USER AND table_name = 'USERS' AND column_name = 'NAME'; \
             IF n = 'N' THEN EXECUTE IMMEDIATE 'ALTER TABLE \"USERS\" MODIFY (\"NAME\" NULL)'; END IF; END;",
            "DECLARE n VARCHAR2(1); BEGIN EXECUTE IMMEDIATE 'ALTER TABLE \"USERS\" MODIFY (\"AGE\" NUMBER(10) DEFAULT NULL)'; \
             SELECT nullable INTO n FROM all_tab_columns WHERE owner = USER AND table_name = 'USERS' AND column_name = 'AGE'; \
             IF n = 'Y' THEN EXECUTE IMMEDIATE 'ALTER TABLE \"USERS\" MODIFY (\"AGE\" NOT NULL)'; END IF; END;",
        ],
    );

    let mut key = Blueprint::alter("users");
    key.big_increments("id").change();
    assert!(key.to_sql(Dialect::MySql).is_err());
    let mut create = Blueprint::create("users");
    create.integer("age").change();
    assert!(create.to_sql(Dialect::Oracle).is_err());
}

#[test]
fn current_time_raw_defaults_and_comments() {
    let mut t = Blueprint::create("events");
    t.datetime("at").use_current().comment("when it's due");
    t.date("on").use_current();
    t.string("code", 10).default_raw("'x'");
    t.ulid("ref");
    t.comment("Event log");
    assert_ddl(
        &t,
        &[
            "CREATE TABLE `events` (`at` DATETIME(6) DEFAULT (UTC_TIMESTAMP(6)) NOT NULL COMMENT 'when it''s due', \
             `on` DATE DEFAULT (UTC_DATE()) NOT NULL, `code` VARCHAR(10) DEFAULT 'x' NOT NULL, `ref` CHAR(26) NOT NULL)",
            "ALTER TABLE `events` COMMENT = 'Event log'",
        ],
        &[
            r#"CREATE TABLE "EVENTS" ("AT" TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL, "ON" DATE DEFAULT TRUNC(SYS_EXTRACT_UTC(SYSTIMESTAMP)) NOT NULL, "CODE" VARCHAR2(10 CHAR) DEFAULT 'x' NOT NULL, "REF" CHAR(26 CHAR) NOT NULL)"#,
            r#"COMMENT ON TABLE "EVENTS" IS 'Event log'"#,
            r#"COMMENT ON COLUMN "EVENTS"."AT" IS 'when it''s due'"#,
        ],
    );

    let mut bad = Blueprint::create("events");
    bad.string("name", 10).use_current();
    let error = bad.to_sql(Dialect::MySql).unwrap_err().to_string();
    assert!(error.contains("use_current"), "{error}");
}

#[test]
fn time_columns_and_use_current_on_update() {
    let mut t = Blueprint::create("shifts");
    t.time("starts").nullable();
    t.datetime("touched").use_current().use_current_on_update();
    assert_ddl(
        &t,
        &["CREATE TABLE `shifts` (`starts` TIME(6), \
           `touched` DATETIME(6) DEFAULT (UTC_TIMESTAMP(6)) ON UPDATE CURRENT_TIMESTAMP(6) NOT NULL)"],
        &[
            r#"CREATE TABLE "SHIFTS" ("STARTS" VARCHAR2(18 CHAR), "TOUCHED" TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL)"#,
        ],
    );

    let mut bad = Blueprint::create("shifts");
    bad.string("name", 10).use_current_on_update();
    let error = bad.to_sql(Dialect::MySql).unwrap_err().to_string();
    assert!(error.contains("use_current_on_update"), "{error}");
}
