//! Connection and table helpers shared by `tests/db` and the local-only
//! `tests/private` suite.

use rustique::{Db, Dialect, Executor};

/// Connects to every configured test database.
pub async fn databases() -> Vec<Db> {
    let mut dbs = Vec::new();
    for var in ["RUSTIQUE_TEST_MYSQL_URL", "RUSTIQUE_TEST_ORACLE_URL"] {
        if let Ok(url) = std::env::var(var) {
            let db = Db::connect(&url)
                .await
                .unwrap_or_else(|e| panic!("{var}: {e}"));
            dbs.push(db);
        }
    }
    if dbs.is_empty() {
        eprintln!("no RUSTIQUE_TEST_*_URL set; skipping database tests");
    }
    dbs
}

/// (Re)creates `table` with an auto-increment `id` key plus `columns`, given as
/// `(name, MySQL type, Oracle type)`.
pub async fn create_table(db: &Db, table: &str, columns: &[(&str, &str, &str)]) {
    let mysql = db.dialect() == Dialect::MySql;
    let id = if mysql {
        "id BIGINT AUTO_INCREMENT PRIMARY KEY"
    } else {
        "id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    };
    drop_table(db, table).await;

    let columns: Vec<String> = columns
        .iter()
        .map(|(name, mysql_type, oracle_type)| {
            format!("{name} {}", if mysql { mysql_type } else { oracle_type })
        })
        .collect();
    let create = format!("CREATE TABLE {table} ({id}, {})", columns.join(", "));
    db.statement(&create, []).await.unwrap();
}

/// Drops `table` if it exists.
pub async fn drop_table(db: &Db, table: &str) {
    let drop = if db.dialect() == Dialect::MySql {
        format!("DROP TABLE IF EXISTS {table}")
    } else {
        format!(
            "BEGIN EXECUTE IMMEDIATE 'DROP TABLE {table}'; \
             EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;"
        )
    };
    db.statement(&drop, []).await.unwrap();
}
