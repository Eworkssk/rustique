#[tokio::test]
async fn busy_pool_makes_queries_wait() {
    for db in databases().await {
        // Oracle's pool holds 10 connections; take them all.
        let mut held = Vec::new();
        for _ in 0..10 {
            held.push(db.begin().await.unwrap());
        }
        let sql = match db.dialect() {
            Dialect::MySql => "SELECT 1 AS n",
            _ => "SELECT 1 AS n FROM dual",
        };
        let waiting = tokio::spawn({
            let db = db.clone();
            async move { db.select(sql, []).await.map(|rows| rows.len()) }
        });
        tokio::task::spawn_blocking(|| std::thread::sleep(Duration::from_millis(300)))
            .await
            .unwrap();
        drop(held);
        assert_eq!(waiting.await.unwrap().unwrap(), 1, "{}", db.dialect());
    }
}

#[tokio::test]
async fn oracle_binds_strings_as_varchar2() {
    for db in databases().await {
        if db.dialect() != Dialect::Oracle {
            continue;
        }
        // An NVARCHAR2 bind would make Oracle skip indexes on VARCHAR2 columns.
        let rows = db
            .select("SELECT DUMP(?, 1016) AS d FROM dual", ["abc".into()])
            .await
            .unwrap();
        let dump: String = rows[0].get("d").unwrap();
        assert!(!dump.contains("AL16UTF16"), "{dump}");
    }
}

#[tokio::test]
async fn counts_over_joins() {
    for db in databases().await {
        create_table(
            &db,
            "orm_h_users",
            &[("name", "VARCHAR(20)", "VARCHAR2(20)")],
        )
        .await;
        create_table(
            &db,
            "orm_h_posts",
            &[
                ("user_id", "BIGINT", "NUMBER(19)"),
                ("name", "VARCHAR(20)", "VARCHAR2(20)"),
            ],
        )
        .await;
        let users = vec![vec!["Ann".into()], vec!["Bo".into()], vec!["Cy".into()]];
        QueryBuilder::table("orm_h_users")
            .insert(&db, &["name"], users)
            .await
            .unwrap();
        let posts = [(1, "a"), (1, "b"), (2, "c")]
            .map(|(user, name)| vec![Value::from(user), Value::from(name)])
            .to_vec();
        QueryBuilder::table("orm_h_posts")
            .insert(&db, &["user_id", "name"], posts)
            .await
            .unwrap();

        let joined = QueryBuilder::table("orm_h_users").join(
            "orm_h_posts",
            "orm_h_users.id",
            "=",
            "orm_h_posts.user_id",
        );
        assert_eq!(joined.clone().limit(2).count(&db).await.unwrap(), 2);
        assert_eq!(
            joined
                .clone()
                .group_by(["orm_h_users.id"])
                .count(&db)
                .await
                .unwrap(),
            2
        );

        let authors = User::query()
            .join("orm_h_posts", "orm_h_users.id", "=", "orm_h_posts.user_id")
            .distinct();
        assert_eq!(authors.count(&db).await.unwrap(), 2);
        let page = authors
            .order_by("orm_h_users.id")
            .paginate(&db, 1, 10)
            .await
            .unwrap();
        assert_eq!(page.total, 2);
        let names: Vec<&str> = page.items.iter().map(|u| u.name.as_str()).collect();
        assert_eq!(names, ["Ann", "Bo"]);
    }
}

