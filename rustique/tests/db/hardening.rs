#[tokio::test]
async fn upsert_counts_only_changed_rows() {
    for db in databases().await {
        create_table(
            &db,
            "orm_h_emails",
            &[("email", "VARCHAR(20)", "VARCHAR2(20)")],
        )
        .await;
        db.statement(
            "CREATE UNIQUE INDEX orm_h_emails_u ON orm_h_emails (email)",
            [],
        )
        .await
        .unwrap();
        let table = QueryBuilder::table("orm_h_emails");
        let rows = |emails: &[&str]| emails.iter().map(|e| vec![Value::from(*e)]).collect();
        table
            .insert(&db, &["email"], rows(&["a", "b"]))
            .await
            .unwrap();

        // Two rows exist and stay as they are; one is new.
        let changed = table
            .upsert(&db, &["email"], rows(&["a", "b", "c"]), &["email"], &[])
            .await
            .unwrap();
        assert_eq!(changed, 1, "{}", db.dialect());
    }
}

#[tokio::test]
async fn bulk_insert_beyond_one_oracle_batch() {
    for db in databases().await {
        create_table(&db, "orm_h_bulk", &[("n", "INT", "NUMBER(10)")]).await;
        let rows: Vec<Vec<Value>> = (0..2500).map(|n| vec![n.into()]).collect();
        let table = QueryBuilder::table("orm_h_bulk");
        let inserted = table.insert(&db, &["n"], rows).await.unwrap();
        assert_eq!(inserted.rows_affected, 2500);
        assert_eq!(table.count(&db).await.unwrap(), 2500);
        assert_eq!(table.sum::<i64>(&db, "n").await.unwrap(), 2499 * 2500 / 2);
    }
}

/// `--all-features` compiles in both rustls providers, so rustls needs one installed.
fn install_crypto_provider() {
    #[cfg(all(feature = "mysql-tls", feature = "mysql-tls-aws-lc-rs"))]
    let _ = rustls::crypto::ring::default_provider().install_default();
}

