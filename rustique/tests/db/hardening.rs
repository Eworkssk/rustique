#[tokio::test]
async fn raw_session_state_does_not_leak_into_pooled_queries() {
    let Ok(url) = std::env::var("RUSTIQUE_TEST_MYSQL_URL") else {
        return;
    };
    // One connection, so every query below gets the same one back.
    let db = rustique::Db::builder(&url)
        .max_connections(1)
        .connect()
        .await
        .unwrap();
    let state = async |db: &rustique::Db| {
        let row = QueryBuilder::table("information_schema.tables")
            .select_raw("@orm_leak AS leak, @@autocommit AS autocommit", [])
            .limit(1)
            .first(db)
            .await
            .unwrap()
            .unwrap();
        let leak: Option<String> = row.get("leak").unwrap();
        (leak, row.get::<i64>("autocommit").unwrap())
    };

    db.statement("SET @orm_leak = 'x'", []).await.unwrap();
    db.statement("SET autocommit = 0", []).await.unwrap();
    assert_eq!(state(&db).await, (None, 1));

    // Hooks and factory callbacks run raw SQL through an `AnyExecutor`.
    db.erase()
        .statement("SET @orm_leak = 'y'", [])
        .await
        .unwrap();
    assert_eq!(state(&db).await, (None, 1));

    // Inside a transaction the state holds until it ends.
    let tx = db.begin().await.unwrap();
    tx.statement("SET @orm_leak = 'z'", []).await.unwrap();
    let rows = tx.select("SELECT @orm_leak AS leak", []).await.unwrap();
    assert_eq!(rows[0].get::<String>("leak").unwrap(), "z");
    tx.commit().await.unwrap();
    assert_eq!(state(&db).await, (None, 1));
}

#[tokio::test]
async fn oracle_raw_session_changes_do_not_reach_pooled_queries() {
    let Ok(url) = std::env::var("RUSTIQUE_TEST_ORACLE_URL") else {
        return;
    };
    // One session at a time, so every query below gets the pooled one.
    let db = rustique::Db::builder(&url)
        .max_connections(1)
        .connect()
        .await
        .unwrap();
    let state = async |db: &rustique::Db| {
        let row = QueryBuilder::table("dual")
            .select_raw(
                "SESSIONTIMEZONE AS tz, SYS_CONTEXT('USERENV', 'CLIENT_INFO') AS info, \
                 SYS_CONTEXT('USERENV', 'SID') AS sid",
                [],
            )
            .first(db)
            .await
            .unwrap()
            .unwrap();
        let state: (String, Option<String>) = (row.get("tz").unwrap(), row.get("info").unwrap());
        (state, row.get::<String>("sid").unwrap())
    };
    let (clean, sid) = state(&db).await;

    // Raw queries cannot change the session, so it stays pooled.
    db.select("SELECT 1 AS n FROM dual", []).await.unwrap();
    assert_eq!(state(&db).await, (clean.clone(), sid));

    db.statement("ALTER SESSION SET TIME_ZONE = '+05:00'", [])
        .await
        .unwrap();
    db.statement(
        "BEGIN DBMS_APPLICATION_INFO.SET_CLIENT_INFO('alice'); END;",
        [],
    )
    .await
    .unwrap();
    assert_eq!(state(&db).await.0, clean);

    // Hooks and factory callbacks run raw SQL through an `AnyExecutor`.
    db.erase()
        .statement("ALTER SESSION SET TIME_ZONE = '+06:00'", [])
        .await
        .unwrap();
    assert_eq!(state(&db).await.0, clean);

    // Inside a transaction the change holds until it ends.
    let tx = db.begin().await.unwrap();
    tx.statement("ALTER SESSION SET TIME_ZONE = '-03:00'", [])
        .await
        .unwrap();
    let rows = tx
        .select("SELECT SESSIONTIMEZONE AS tz FROM dual", [])
        .await
        .unwrap();
    assert_eq!(rows[0].get::<String>("tz").unwrap(), "-03:00");
    tx.commit().await.unwrap();
    assert_eq!(state(&db).await.0, clean);
}

#[tokio::test]
async fn keep_sessions_after_raw_sql_skips_the_reset() {
    for (var, set, read) in [
        (
            "RUSTIQUE_TEST_MYSQL_URL",
            "SET @orm_keep = 'kept'",
            "@orm_keep AS v FROM information_schema.tables",
        ),
        (
            "RUSTIQUE_TEST_ORACLE_URL",
            "BEGIN DBMS_APPLICATION_INFO.SET_CLIENT_INFO('kept'); END;",
            "SYS_CONTEXT('USERENV', 'CLIENT_INFO') AS v FROM dual",
        ),
    ] {
        let Ok(url) = std::env::var(var) else {
            continue;
        };
        let db = rustique::Db::builder(&url)
            .max_connections(1)
            .keep_sessions_after_raw_sql()
            .connect()
            .await
            .unwrap();
        let (table, column) = read.split_once(" FROM ").map(|(c, t)| (t, c)).unwrap();
        let value = async |db: &rustique::Db| -> Option<String> {
            let row = QueryBuilder::table(table).select_raw(column, []).limit(1);
            row.first(db).await.unwrap().unwrap().get("v").unwrap()
        };

        db.statement(set, []).await.unwrap();
        assert_eq!(value(&db).await.as_deref(), Some("kept"), "{var}");

        // Oracle transactions keep the session too; MySQL ones still reset.
        let tx = db.begin().await.unwrap();
        tx.statement(&set.replace("kept", "in tx"), [])
            .await
            .unwrap();
        tx.commit().await.unwrap();
        let expected = (var == "RUSTIQUE_TEST_ORACLE_URL").then_some("in tx");
        assert_eq!(value(&db).await.as_deref(), expected, "{var}");
        db.disconnect().await.unwrap();
    }
}
