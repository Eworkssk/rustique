#[tokio::test]
async fn busy_pool_times_out() {
    for var in ["RUSTIQUE_TEST_MYSQL_URL", "RUSTIQUE_TEST_ORACLE_URL"] {
        let Ok(url) = std::env::var(var) else {
            continue;
        };
        let db = rustique::Db::builder(&url)
            .min_connections(1)
            .max_connections(1)
            .acquire_timeout(Duration::from_millis(300))
            .idle_timeout(Duration::from_secs(60))
            .max_lifetime(Duration::from_secs(600))
            .connect()
            .await
            .unwrap_or_else(|e| panic!("{var}: {e}"));

        let tx = db.begin().await.unwrap(); // holds the only connection
        let started = std::time::Instant::now();
        let busy = db.select("SELECT 1 AS n FROM dual", []).await;
        assert!(busy.is_err(), "{var}: {busy:?}");
        assert!(started.elapsed() < Duration::from_secs(5), "{var}");

        tx.commit().await.unwrap();
        db.select("SELECT 1 AS n FROM dual", []).await.unwrap();
    }
}

#[tokio::test]
async fn oracle_timeout_cancels_the_query_on_the_server() {
    let Ok(url) = std::env::var("RUSTIQUE_TEST_ORACLE_URL") else {
        return;
    };
    let db = rustique::Db::builder(&url)
        .max_connections(1)
        .connect()
        .await
        .unwrap();
    // Runs for minutes. (`DBMS_SESSION.SLEEP` would not do: it ignores breaks.)
    let slow = "SELECT COUNT(*) AS c FROM all_objects a, all_objects b, all_objects c";

    // Pool: the only connection is free again right away.
    let started = std::time::Instant::now();
    let timed_out = tokio::time::timeout(Duration::from_millis(300), db.select(slow, [])).await;
    assert!(timed_out.is_err());
    db.select("SELECT 1 AS n FROM dual", []).await.unwrap();
    assert!(
        started.elapsed() < Duration::from_secs(5),
        "{:?}",
        started.elapsed()
    );

    // Transaction: the statement is cancelled, the transaction lives on.
    create_table(&db, "orm_h_cancel", &[("n", "INT", "NUMBER(10)")]).await;
    let table = QueryBuilder::table("orm_h_cancel");
    let tx = db.begin().await.unwrap();
    table
        .insert(&tx, &["n"], vec![vec![1.into()]])
        .await
        .unwrap();
    let started = std::time::Instant::now();
    let timed_out = tokio::time::timeout(Duration::from_millis(300), tx.select(slow, [])).await;
    assert!(timed_out.is_err());
    assert_eq!(table.count(&tx).await.unwrap(), 1);
    assert!(
        started.elapsed() < Duration::from_secs(5),
        "{:?}",
        started.elapsed()
    );
    tx.commit().await.unwrap();
    assert_eq!(table.count(&db).await.unwrap(), 1);
}

#[tokio::test]
async fn mysql_timeout_kills_the_query_on_the_server() {
    let Ok(url) = std::env::var("RUSTIQUE_TEST_MYSQL_URL") else {
        return;
    };
    let db = rustique::Db::builder(&url)
        .max_connections(1)
        .connect()
        .await
        .unwrap();
    let slow = "SELECT SLEEP(5) AS s, 'orm-kill-on-drop' AS marker";
    let timed_out = tokio::time::timeout(Duration::from_millis(200), db.select(slow, [])).await;
    assert!(timed_out.is_err());

    let watcher = rustique::Db::connect(&url).await.unwrap();
    let running = "SELECT COUNT(*) AS n FROM information_schema.processlist \
                   WHERE info LIKE '%orm-kill-on-drop%' AND info NOT LIKE '%processlist%'";
    let started = std::time::Instant::now();
    loop {
        let rows = watcher.select(running, []).await.unwrap();
        if rows[0].get::<i64>("n").unwrap() == 0 {
            break;
        }
        assert!(started.elapsed() < Duration::from_secs(1), "still running");
        tokio::time::sleep(Duration::from_millis(50)).await;
    }

    // The pool's only connection works again, without the kill's error.
    let rows = db.select("SELECT 1 AS n", []).await.unwrap();
    assert_eq!(rows[0].get::<i64>("n").unwrap(), 1);
    assert!(started.elapsed() < Duration::from_secs(1));
}

