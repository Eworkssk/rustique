SET FEEDBACK OFF

BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN ('BENCH_EVENTS', 'BENCH_POSTS', 'BENCH_USERS')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' PURGE';
    END LOOP;
END;
/

WHENEVER SQLERROR EXIT FAILURE

CREATE TABLE bench_users (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(255) NOT NULL,
    email VARCHAR2(255) NOT NULL,
    age NUMBER(10) NOT NULL,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6)
);
CREATE INDEX bench_users_age ON bench_users (age);

CREATE TABLE bench_posts (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER(19) NOT NULL,
    title VARCHAR2(255) NOT NULL,
    body CLOB NOT NULL,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6)
);
CREATE INDEX bench_posts_user_id ON bench_posts (user_id);

CREATE TABLE bench_events (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER(19) NOT NULL,
    payload CLOB NOT NULL CHECK (payload IS JSON),
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6)
);

INSERT /*+ APPEND */ INTO bench_users (id, name, email, age, created_at, updated_at)
SELECT n, 'User ' || n, 'user' || n || '@example.com', 18 + MOD(n, 60), SYS_EXTRACT_UTC(SYSTIMESTAMP), SYS_EXTRACT_UTC(SYSTIMESTAMP)
FROM (SELECT (a.n - 1) * 1000 + b.n AS n
      FROM (SELECT LEVEL n FROM dual CONNECT BY LEVEL <= 100) a
      CROSS JOIN (SELECT LEVEL n FROM dual CONNECT BY LEVEL <= 1000) b);
COMMIT;

-- Post ids 1..10 belong to user 1, 11..20 to user 2, ...
INSERT /*+ APPEND */ INTO bench_posts (id, user_id, title, body, created_at, updated_at)
SELECT n, 1 + TRUNC((n - 1) / 10), 'Post ' || n, TO_CLOB(RPAD('lorem ipsum ', 120, 'lorem ipsum ')), SYS_EXTRACT_UTC(SYSTIMESTAMP), SYS_EXTRACT_UTC(SYSTIMESTAMP)
FROM (SELECT (a.n - 1) * 1000 + b.n AS n
      FROM (SELECT LEVEL n FROM dual CONNECT BY LEVEL <= 1000) a
      CROSS JOIN (SELECT LEVEL n FROM dual CONNECT BY LEVEL <= 1000) b);
COMMIT;

INSERT /*+ APPEND */ INTO bench_events (id, user_id, payload, created_at, updated_at)
SELECT n, 1 + MOD(n - 1, 100000),
    JSON_OBJECT(
        'type' VALUE DECODE(MOD(n, 5), 0, 'click', 1, 'view', 2, 'purchase', 3, 'signup', 'logout'),
