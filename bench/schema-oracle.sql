        'items' VALUE JSON_ARRAY(JSON_OBJECT('sku' VALUE 'A1', 'qty' VALUE 2), JSON_OBJECT('sku' VALUE 'B2', 'qty' VALUE 1))
    ),
    SYS_EXTRACT_UTC(SYSTIMESTAMP), SYS_EXTRACT_UTC(SYSTIMESTAMP)
FROM (SELECT (a.n - 1) * 1000 + b.n AS n
      FROM (SELECT LEVEL n FROM dual CONNECT BY LEVEL <= 100) a
      CROSS JOIN (SELECT LEVEL n FROM dual CONNECT BY LEVEL <= 1000) b);
COMMIT;

